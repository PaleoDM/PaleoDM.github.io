      <Section title="Introduction: The Promise and Limits of Targeted Universalism in Financial Aid">
        <p>
          Online higher education has expanded access to historically
          underserved populations at an unprecedented scale. Yet access has not
          produced equitable outcomes. Retention and graduation gaps persist
          along the same demographic and socioeconomic lines that expanded access
          was supposed to address (Bettinger et al., 2017; Hart et al., 2018).
          The paradox is now well documented: institutions can open the door
          wider without changing who makes it through.
        </p>
        <p>
          The principle of targeted universalism offers a framework for
          understanding why. Developed by john a. powell and colleagues,
          targeted universalism holds that universal goals — such as equitable
          degree completion — require strategies that are deliberately
          differentiated to the specific barriers facing distinct subgroups
          (powell, 2012; powell et al., 2019). It rejects the premise that
          treating everyone the same produces equal results. When barriers are
          unequally distributed, universal approaches disproportionately benefit
          the already-advantaged.
        </p>
        <p>
          Applied to financial aid, the framework has primarily been used to ask{" "}
          <em>who</em> should receive differentiated support. Research
          consistently shows that low-income, first-generation, and racially
          minoritized students face the steepest financial barriers and benefit
          most from targeted aid (Dynarski and Scott-Clayton, 2013;
          Goldrick-Rab, 2016). This subgroup-level differentiation is the core
          contribution of targeted universalism to higher education equity work.
        </p>
        <p>
          But there is a second dimension that has received less attention:{" "}
          <em>when</em>. The leaky pipeline metaphor describes how systemic
          barriers compound across the student lifecycle (Tinto, 1993).
          Financial vulnerability does not hold a constant shape from enrollment
          to graduation. A first-term student deciding whether to re-enroll
          faces a different financial calculus than a near-completer who needs
          one more course but cannot afford another billing term. If targeted
          universalism demands strategies calibrated to specific barriers, and
          the barriers themselves change across the lifecycle, then full
          application of the framework requires differentiation not only by
          subgroup but by stage.
        </p>
        <p>
          This white paper synthesizes evidence from two empirical studies
          conducted at Western Governors University, a large, fully online,
          competency-based institution. The first examines financial aid and
          retention at the earliest major attrition point — the transition from
          Term 1 to Term 2 (Peredo et al., in review). The second examines
          financial aid and attrition at the latest — students who withdraw
          within 15 competency units of completing their degree (Peredo and
          Cain, in review). Viewed together, these studies reveal that the
          equity-aid gap — the structural mismatch between financial need and
          institutional support — is not a stage-specific anomaly. It is a
          systemic pattern that targeted universalism both predicts and demands a
          response to.
        </p>
      </Section>

